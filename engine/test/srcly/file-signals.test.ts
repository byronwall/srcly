import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { fileSignalsOp, srclyView } from "../../src/srcly/ops/file-signals";
import { createEngineSession } from "../../src/srcly/session";
import { chooseTypescript } from "../../src/srcly/typescript-choice";

const root = fileURLToPath(new URL("../../examples/bad-ish-solid", import.meta.url));
const source = path.join(root, "src");
const session = createEngineSession({ root, source, tsconfig: null, typescriptFrom: chooseTypescript(root, source).from });
const result = fileSignalsOp(session, {});

describe("fileSignals carries tsx-data-flow's reporting into srcly (M7)", () => {
  it("finds each type-impossible guard once, in the file that holds it", () => {
    const defenses = result.findings.filter((f) => f.rule === "impossible-defense");
    expect(defenses.map((f) => `${f.file}:${f.line}`)).toEqual([
      "src/DashboardShell.tsx:12",
      "src/DashboardShell.tsx:13",
      "src/DashboardShell.tsx:51",
      "src/DashboardShell.tsx:52",
      "src/DashboardShell.tsx:53",
      "src/DashboardShell.tsx:68",
      "src/DashboardShell.tsx:68",
      "src/DashboardShell.tsx:110",
      "src/DashboardShell.tsx:111",
      "src/DashboardShell.tsx:133",
      "src/DashboardShell.tsx:134",
      "src/DashboardShell.tsx:135",
    ]);
    expect(defenses[0].message).toContain('`route.toolbar.theme ?? "light"`');
    expect(result.unplacedDefenses).toBe(0);
    const metrics = Object.fromEntries(result.files.map((f) => [f.file, f.metrics]));
    expect(metrics["src/DashboardShell.tsx"].impossibleDefenses).toBe(12);
    expect(metrics["src/view-models.ts"].impossibleDefenses).toBe(0);
  });

  it("finds Chart's repeated fork on props.type, Solid <Match> sites included", () => {
    const forks = result.findings.filter((f) => f.rule === "repeated-fork");
    expect(forks).toEqual([
      expect.objectContaining({ file: "src/Chart.tsx", line: 37, endLine: 48 }),
    ]);
    expect(forks[0].message).toContain("`props.type` at 4 sibling branch sites (lines 37, 38, 45, 48)");
  });

  it("reports a parent that relays context-like props, or a broad prop bundle, to a same-feature child", () => {
    const root = fileURLToPath(new URL("./__fixtures__/context-relay", import.meta.url));
    const source = path.join(root, "src");
    const relay = fileSignalsOp(createEngineSession({ root, source, tsconfig: null, typescriptFrom: chooseTypescript(root, source).from }), {});
    expect(relay.findings.map((f) => `${f.rule} ${f.file}:${f.line}`)).toEqual([
      "broad-prop-bundle src/notes/NotesPage.tsx:10",
      "context-relay src/notes/NotesPage.tsx:11",
    ]);
    expect(relay.findings[1].message).toContain("Relays `workspace`, `settings` to `NoteList`");
    expect(result.findings.some((f) => f.rule === "context-relay" || f.rule === "broad-prop-bundle")).toBe(false);
  });

  it("measures every program file, the worst render path per file", () => {
    expect(result.files.map((f) => f.file)).toEqual(["src/Chart.tsx", "src/DashboardShell.tsx", "src/types.ts", "src/view-models.ts"]);
    const shell = result.files.find((f) => f.file === "src/DashboardShell.tsx")!.metrics;
    expect(shell).toMatchObject({ pathDepth: 15, relayHops: 6, representationChanges: 8 });
    expect(shell.fanOut).toBeGreaterThan(1);
  });

  it("writes dataflow.md from the old CLI's views, with srcly's provenance and footer", () => {
    // Each view's text is the old CLI's, byte for byte (checked against the archived
    // tsx-data-flow on this example at --max-items 8); here only srcly's changes.
    expect(srclyView("# Title\n\n> Generated by **tsx-dataflow**, x\n\n```\n# kept\n```\n\n---\n\n_Regenerate this report:_\n")).toBe(
      "## Title\n\n> Generated by **srcly**'s data-flow engine, x\n\n```\n# kept\n```\n",
    );
    expect(result.markdown).not.toContain("tsx-dataflow");
    expect(result.markdown).toContain("### WORK ITEM DF-001");
    expect(result.markdown).toContain("### Stop Recommendation");
  });
});
