import path from "node:path";
import { z } from "zod";
import { libraryModelFileSchema } from "../../analysis/library-models";
import { CONTRACTS } from "./registry";

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: boolean | JsonSchema;
  items?: JsonSchema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  description?: string;
};

/** The files `pnpm emit-contracts` writes, keyed by path relative to the srcly repository root. */
export function emitContracts(): Map<string, string> {
  const files = new Map<string, string>();
  const types: string[] = [
    "// Generated by `cd engine && pnpm emit-contracts` from engine/src/srcly/contracts.",
    "// Do not edit by hand; engine/test/srcly/contracts-current.test.ts checks it.",
    "",
  ];
  for (const contract of CONTRACTS) {
    const schema = z.toJSONSchema(contract.schema, { target: "draft-2020-12" }) as JsonSchema & Record<string, unknown>;
    files.set(
      path.posix.join("server/app/services/dataflow/contracts", `${contract.op}.schema.json`),
      `${JSON.stringify({ title: contract.typeName, ...schema }, null, 2)}\n`,
    );
    types.push(`/** Result of the \`${contract.op}\` op. */`);
    types.push(`export type ${contract.typeName} = ${printType(schema, 0)};`, "");
  }
  files.set("client/src/dataflow/contract.generated.ts", types.join("\n"));
  // The library model row files' schema (`engine/models/*.json` point at it with `$schema`).
  const models = z.toJSONSchema(libraryModelFileSchema, { target: "draft-2020-12" });
  files.set("engine/models/library-models.schema.json", `${JSON.stringify({ title: "LibraryModelFile", ...models }, null, 2)}\n`);
  return files;
}

function printType(schema: JsonSchema, depth: number): string {
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map((member) => printType(member, depth)).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map((type) => printType({ ...schema, type }, depth)).join(" | ");
  switch (schema.type) {
    case "string": return "string";
    case "number":
    case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      const item = printType(schema.items ?? {}, depth);
      return /[|&]/.test(item) && !item.startsWith("{") ? `(${item})[]` : `${item}[]`;
    }
    case "object": return printObject(schema, depth);
    default: return "unknown";
  }
}

function printObject(schema: JsonSchema, depth: number): string {
  const entries = Object.entries(schema.properties ?? {});
  if (entries.length === 0) {
    return typeof schema.additionalProperties === "object" ? `Record<string, ${printType(schema.additionalProperties, depth)}>` : "Record<string, never>";
  }
  const required = new Set(schema.required ?? []);
  const indent = "  ".repeat(depth + 1);
  const lines = entries.map(([name, value]) => {
    const doc = value.description ? `${indent}/** ${value.description} */\n` : "";
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    return `${doc}${indent}${key}${required.has(name) ? "" : "?"}: ${printType(value, depth + 1)};`;
  });
  return `{\n${lines.join("\n")}\n${"  ".repeat(depth)}}`;
}
